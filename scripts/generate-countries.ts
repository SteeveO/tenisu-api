/**
 * Generates src/domain/countries.generated.ts, the country reference data.
 * Run once, and again only when scripts/ioc-to-iso.ts changes: the domain then
 * ships plain data and keeps zero dependencies (D33).
 *
 * Fails if a country has no French name or no flag, so that every code accepted
 * by the API is guaranteed to be displayable.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import countries from 'i18n-iso-countries';
import french from 'i18n-iso-countries/langs/fr.json' with { type: 'json' };
import { format, resolveConfig } from 'prettier';
import { IOC_TO_ISO } from './ioc-to-iso';

const root = join(import.meta.dirname, '..');
const outputPath = join(root, 'src/domain/countries.generated.ts');
const flagsDirectory = join(root, 'node_modules/flag-icons/flags/4x3');

countries.registerLocale(french);

const entries = Object.entries(IOC_TO_ISO)
  .toSorted(([a], [b]) => a.localeCompare(b))
  .map(([iocCode, isoCode]) => {
    const name = countries.getName(isoCode, 'fr');
    if (name === undefined) {
      throw new Error(`No French name for ${iocCode} (${isoCode})`);
    }
    if (!existsSync(join(flagsDirectory, `${isoCode.toLowerCase()}.svg`))) {
      throw new Error(`No flag for ${iocCode} (${isoCode})`);
    }
    return { iocCode, isoCode, name };
  });

const source = `// Generated by scripts/generate-countries.ts. Do not edit by hand.
import type { Country } from './country';

export const COUNTRIES: readonly Country[] = ${JSON.stringify(entries)};
`;

const prettierOptions = await resolveConfig(outputPath);
writeFileSync(outputPath, await format(source, { ...prettierOptions, filepath: outputPath }));
console.log(`Wrote ${String(entries.length)} countries to ${outputPath}`);
